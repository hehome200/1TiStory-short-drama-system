import type { OutlineFactSheet, SourceSections } from "@/lib/types";

type PromptBundle = {
  system: string;
  user: string;
};

const STRUCTURED_SUMMARY_SCHEMA =
  '{"structuredSummary":{"oneLineSummary":"string","coreConflict":{"external":"string","internal":"string","relational":"string"},"keyRelationships":[{"personA":"string","personB":"string","relationshipType":"亲情 | 爱情 | 友情 | 敌对 | 利用 | 竞争 | 其他","description":"string","arcDirection":"恶化 | 缓和 | 破裂 | 修复 | 反转"}],"narrativeStructure":{"narrativeMode":"linear|nonlinear","nonlinearType":"flashback|in_medias_res|intercut|parallel|unknown","openingType":"conflict_first|daily_life|backstory|mystery_hook","isTimelineStart":true,"hasBackstoryToRecover":false,"backstoryHint":"string"},"longArcNodes":[{"nodeLabel":"string","placementHint":"前期 | 中前期 | 中期 | 中后期 | 后期 | 终局 | 未知","description":"string","arcType":"setup|rising|climax|falling|resolution|twist","confidence":"high|medium|low"}],"hiddenReveals":[{"revealLabel":"string","revealContent":"string","plannedPhase":"前期 | 中期 | 后期 | 终局 | 未知","spoilerRiskLevel":"high|medium|low"}]},"fieldConfidence":{"oneLineSummary":"high|medium|low","coreConflict":"high|medium|low","keyRelationships":"high|medium|low","narrativeStructure":"high|medium|low","longArcNodes":"high|medium|low","hiddenReveals":"high|medium|low"},"warnings":["string"],"missingFields":["string"]}';

export function buildStructuredSummaryFromFactSheetPrompt(
  factSheet: OutlineFactSheet,
  sourceSections?: SourceSections,
  currentMacro?: string,
): PromptBundle {
  const system = [
    "你是一个结构化总纲提炼器。基于已提取的事实库（factSheet）生成 6 个核心字段的结构化总纲。",
    "",
    "【输入说明】",
    "你的主要输入是事实库（factSheet），它已经从大纲原文中提取了结构化的事实项。",
    "你的任务是将这些事实项组织成结构化总纲，而非重新从原文提取。",
    "",
    "【必须严格遵守的输出格式】",
    "你只能返回一个 JSON 对象。顶层必须是 {}，绝对不能是 []。",
    "",
    `返回结构：${STRUCTURED_SUMMARY_SCHEMA}`,
    "",
    "【必填字段】必须全部 6 个字段都出现：",
    "1. oneLineSummary - 一句话主线（空字符串占位）",
    "2. coreConflict - 核心冲突 { external, internal, relational }（三个子字段都为空字符串时即视为缺失）",
    "3. keyRelationships - 关键人物关系数组（空数组 [] 占位）",
    "4. narrativeStructure - 叙事结构 { narrativeMode, openingType, isTimelineStart, hasBackstoryToRecover }",
    "5. longArcNodes - 长线剧情节点数组（空数组 [] 占位）",
    "6. hiddenReveals - 不可提前揭示信息数组（空数组 [] 占位）",
    "",
    "【fieldConfidence - 必填】对每个字段标注置信度（high/medium/low）：",
    "- high：事实库中有明确对应数据，你只是整理映射",
    "- medium：事实库中有部分数据，你做了推断补全",
    "- low：事实库中信息不足，你大量推断或猜测",
    "",
    "【关键语义规则——audienceRevealState（最高优先级）】",
    "事实库中每个事实项都标注了 audienceRevealState，表示该信息在故事叙事中对观众的揭示状态。",
    "你必须严格区分「观众视角」和「上帝视角」——结构化总纲面向的是观众视角。",
    "",
    "■ audienceRevealState=not_yet_revealed（绝对禁区）：",
    "  这些信息是故事刻意对观众隐瞒的秘密，包括但不限于：隐藏身份、真实动机、秘密关系、未揭露的过往。",
    "  → 绝对不可出现在 oneLineSummary、coreConflict（external/internal/relational）、narrativeStructure 中",
    "  → 不可用任何变体表达（如「隐姓埋名」「秘密潜入」「为报仇而…」「恋人惨死」「旧案真相」等暗示性措辞）",
    "  → 不可使用括号别名格式，如「王世锦（陆见）」「陆见（王世锦）」——只能使用观众开场认知的名字",
    "  → 必须进入 hiddenReveals，spoilerRiskLevel=high",
    "  → 写 oneLineSummary/coreConflict/narrativeStructure 时，假装你完全不知道这些信息存在",
    "",
    "■ audienceRevealState=revealed_at_start（可自由使用）：",
    "  观众开场就知道的公开信息，可以直接用于 oneLineSummary 和 coreConflict。",
    "",
    "■ audienceRevealState=gradual_reveal（谨慎使用）：",
    "  在故事进程中逐步揭示的信息。",
    "  → 在 hiddenReveals 中标注对应的 plannedPhase",
    "  → oneLineSummary/coreConflict 中只能使用观众在开场已能感知的表层表现，不可提前揭示底层真相",
    "",
    "【观众安全写作检查清单】",
    "写完 oneLineSummary、coreConflict（三个子字段）和 narrativeStructure 后，逐条检查：",
    "1. 是否包含任何 not_yet_revealed 事实的内容或暗示？→ 如果是，必须删除或改写",
    "2. 角色的真实身份/动机是否被泄露？→ 用观众开场认知的身份替代",
    "3. 是否使用了「隐姓埋名」「伪装」「真实身份」「秘密」「报仇」「恋人惨死」等暗示存在隐藏信息的措辞？→ 删除",
    "4. 是否出现了「A（B）」格式的括号别名？→ 删除括号部分，只保留观众认知的名字",
    "5. coreConflict.internal 中是否暴露了角色的隐藏动机或真实身世？→ 改为观众可感知的表面矛盾",
    "",
    "【占位规则】信息不足时保留键名，用空字符串或空数组占位，不要跳过任何字段。",
    "",
    "【禁止事项】",
    "禁止返回数组（顶层不能是 []）",
    "禁止只返回部分字段（必须 6 个字段全部出现）",
    "禁止输出 Markdown、解释、额外文字",
    "",
    "如果某个字段无法提取：填空值占位 + 标注 low confidence + 在 missingFields 中列出字段名。",
  ].join("\n");

  const userParts: string[] = [
    "请基于以下事实库生成结构化总纲。",
    "",
    "=== 字段映射指南 ===",
    "",
    "1. oneLineSummary（40-90 字）：",
    "   来源：仅使用 audienceRevealState=revealed_at_start 的 characterFacts（identity/personality 类）+ 主线 eventFacts",
    "   格式：主角（观众开场认知的身份）+ 表面目标 + 主要障碍",
    "   ⚠ 禁止：不得包含 not_yet_revealed 的任何内容——包括隐藏身份、真实动机、秘密关系",
    "   ⚠ 禁止：不得使用「隐姓埋名」「伪装身份」「为报仇」等暗示存在秘密的措辞",
    "   ⚠ 写法：假设你是一个只看了前 2 集的观众，用你此刻知道的信息写这句话",
    "",
    "2. coreConflict（三分法）：",
    "   - external：来自 eventFacts（incident/climax 类）+ characterFacts（motive 类，仅 audienceRevealState=revealed_at_start）",
    "   - internal：来自 characterFacts（motive/personality 类）中观众可感知的表面内心矛盾，不可暴露隐藏动机或真实身世",
    "   - relational：来自 relationshipFacts（敌对/竞争/利用类），只使用观众开场认知的人物名字",
    "   ⚠ 禁止：三个子字段均不得泄露 not_yet_revealed 的动机、身份或身世",
    "   ⚠ 禁止：不得使用括号别名格式如「王世锦（陆见）」，只能使用观众认知的单一名字",
    "",
    "3. keyRelationships（3-8 条）：",
    "   来源：relationshipFacts 直接映射",
    "   映射：personA → personA, personB → personB, relationshipType → relationshipType, content → description, arcDirection → arcDirection",
    "",
    "4. narrativeStructure：",
    "   来源：timelineNotes",
    "   映射：",
    "   - isTimelineStart → isTimelineStart",
    "   - hasBackstory → hasBackstoryToRecover",
    "   - backstoryHint → backstoryHint",
    "   - nonlinearHint → 推断 narrativeMode（有 nonlinearHint 则 nonlinear，否则 linear）和 nonlinearType",
    "   - openingType：根据故事开场特征推断（conflict_first/daily_life/backstory/mystery_hook）",
    "",
    "5. longArcNodes（5-10 个）：",
    "   来源：eventFacts",
    "   映射：content → description, eventCategory → arcType（backstory→setup, setup→setup, incident→rising, turning_point→twist, climax→climax, other→rising）",
    "   placementHint：根据事件在故事中的位置推断（前期/中前期/中期/中后期/后期/终局/未知）",
    "",
    "6. hiddenReveals（3-8 条）：",
    "   来源：revealFacts 直接映射",
    "   映射：revealLabel → revealLabel, content → revealContent, plannedRevealPhase → plannedPhase, spoilerRisk → spoilerRiskLevel",
    "   补充：characterFacts 中 audienceRevealState=not_yet_revealed 且 factCategory=hidden_identity 的条目也应作为 hiddenReveals",
    "",
    "=== 部分成功策略 ===",
    "字段无法可靠提取时：填空值占位 → 在 warnings 中说明 → 在 missingFields 中列字段名。",
    "硬约束：信息不足不要硬编。",
    "",
    "=== 事实库 ===",
    "",
    `characterFacts (${factSheet.characterFacts.length} 项)：`,
    JSON.stringify(factSheet.characterFacts, null, 2),
    "",
    `eventFacts (${factSheet.eventFacts.length} 项)：`,
    JSON.stringify(factSheet.eventFacts, null, 2),
    "",
    `relationshipFacts (${factSheet.relationshipFacts.length} 项)：`,
    JSON.stringify(factSheet.relationshipFacts, null, 2),
    "",
    `revealFacts (${factSheet.revealFacts.length} 项)：`,
    JSON.stringify(factSheet.revealFacts, null, 2),
    "",
    `timelineNotes (${factSheet.timelineNotes.length} 项)：`,
    JSON.stringify(factSheet.timelineNotes, null, 2),
    "",
    `warnings：${JSON.stringify(factSheet.warnings)}`,
  ];

  if (sourceSections?.storySynopsisText?.trim()) {
    userParts.push(
      "",
      "=== 补充参考：故事梗概前 3000 字（仅供上下文参考，事实库为主要依据）===",
      sourceSections.storySynopsisText.slice(0, 3000),
    );
  }

  if (currentMacro?.trim()) {
    userParts.push(
      "",
      "=== 补充参考：用户当前总纲前 2000 字（仅供参考，不要照搬）===",
      currentMacro.slice(0, 2000),
    );
  }

  return { system, user: userParts.join("\n") };
}
