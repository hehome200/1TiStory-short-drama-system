const tabs: { id: RewriteStep; label: string }[] = [
  { id: "infoflow", label: "信息流" },
  { id: "overview", label: "故事梗概" },
  { id: "characters", label: "人物小传" },
  { id: "outlines", label: "分集大纲" },
  { id: "script", label: "剧本正文" },
];

